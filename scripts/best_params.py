#!/usr/bin/env python3
"""Write the best hyperparameters per paper model, averaged over datasets.

Uses nested search results for cross-subject and block search results for
within-subject classification. Output: `fnirsatlas/configs/best_params_{setting}.yaml`.

Example:
    uv run python scripts/best_params.py -c within
"""

import argparse

import yaml

from fnirsatlas.config import get_paper_models
from fnirsatlas.utils import CONFIG_DIR
from fnirsatlas.dataset_catalog import get_available_datasets
from fnirsatlas.search_results import best_params, load_search_data

SEARCH_STRATEGIES = {"cross": "nested", "within": "block"}


def collect_params(datasets, seeds, setting, metric):
    """Return the best search parameters of each paper model."""
    params = {}
    for model in get_paper_models():
        data = load_search_data(
            datasets, model, seeds, setting, SEARCH_STRATEGIES[setting], metric
        )
        if data is None:
            raise ValueError(f"No search results for {model}")
        missing = sorted(set(datasets) - set(data.dataset))
        if missing:
            raise ValueError(f"No {model} search results for {missing}")
        params[model] = best_params(data)
    return params


def main():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "-c", "--setting", choices=SEARCH_STRATEGIES, required=True,
        help="Classification setting whose search results are used",
    )
    parser.add_argument(
        "-d", "--datasets", nargs="+", default=get_available_datasets(),
        help="Datasets to average over (default: all)",
    )
    parser.add_argument(
        "--seeds", nargs="+", type=int, default=list(range(5)),
        help="Seeds to average over (default: 0-4)",
    )
    parser.add_argument(
        "--metric", default="kappa", help="Selection metric (default: kappa)"
    )
    args = parser.parse_args()
    params = collect_params(args.datasets, args.seeds, args.setting, args.metric)
    header = (
        f"# Generated by scripts/best_params.py -c {args.setting}: parameters with the "
        f"highest mean {args.metric} over datasets "
        f"({SEARCH_STRATEGIES[args.setting]} search).\n"
    )
    content = {"datasets": args.datasets, "seeds": args.seeds, "params": params}
    output = CONFIG_DIR / f"best_params_{args.setting}.yaml"
    output.write_text(header + yaml.safe_dump(content, sort_keys=False))


if __name__ == "__main__":
    main()
