"""Luke2021 FRESH auditory speech fNIRS dataset."""

import shutil
from pathlib import Path

from moabb.datasets import download as dl
from moabb.datasets.metadata.schema import (
    DatasetMetadata,
    DataStructureMetadata,
    DocumentationMetadata,
    ExperimentMetadata,
    ParticipantMetadata,
)

from .bids_base import BaseBIDSFNIRSDataset, get_bids_cache_root
from .metadata import FnirsAcquisitionMetadata
from .utils import extract_archive

DOI = "10.1117/1.NPh.8.2.025008"
DATA_DOI = "10.17605/OSF.IO/B4WCK"
URL = "https://osf.io/download/xd2qm/"
CODE = "Luke2021FnirsSpeech"
TASK = "FRESHAUDIO"
SUBJECTS = list(range(1, 18))
EVENTS = {"Control": 1, "Noise": 2, "Speech": 3}
PARADIGM = "fnirsSpeech"
# BIDS sidecar SamplingFrequency.
SFREQ = 5.208333333333333
N_TRIALS_PER_CLASS = 20
# Onsets are at least 14.976 s apart.
INTERVAL = [-2, 12.9]


class Luke2021FnirsSpeech(BaseBIDSFNIRSDataset):
    """FRESH auditory control, noise, and speech recordings.

    Passive listening to speech (three sentences, 5.25 s), 300-700 Hz noise
    (5 s) and silence (5 s) in random order with 10-20 s inter-stimulus
    intervals [1]_. Released as Dataset I of the fNIRS Reproducibility Study
    Hub [2]_.

    References
    ----------
    .. [1] Luke, R., Larson, E., Shader, M. J., Innes-Brown, H., Van Yper, L.,
           Lee, A. K. C., Sowman, P. F., & McAlpine, D. (2021). Analysis
           methods for measuring passive auditory fNIRS responses generated by
           a block-design paradigm. Neurophotonics, 8(2), 025008.
    .. [2] Yücel, M. A., Luke, R., Mesquita, R. C., von Lühmann, A., et al.
           (2025). fNIRS reproducibility varies with data quality, analysis
           pipelines, and researcher experience. Communications Biology, 8,
           1149.
    """

    METADATA = DatasetMetadata(
        acquisition=FnirsAcquisitionMetadata(
            sampling_rate=SFREQ,
            # 25 long and 8 short pairs. The paper reports 24 long pairs.
            channel_types={"fnirs_cw_amplitude": 66},
            hardware="NIRx NIRScoutX with APD detectors",
            line_freq=50.0,
            montage="custom",
            wavelengths_nm=[760.0, 850.0],
            n_sources=12,
            # 12 detectors plus 8 short detectors.
            n_detectors=20,
            n_short_channels=8,
            sensor_positions="3d",
            other_modalities=[],
        ),
        # Sex and handedness are n/a in participants.tsv.
        participants=ParticipantMetadata(
            n_subjects=len(SUBJECTS),
            age_min=22.0,
            age_max=40.0,
        ),
        experiment=ExperimentMetadata(
            paradigm=PARADIGM,
            task_type="passive auditory listening",
            events=EVENTS,
            n_classes=len(EVENTS),
            class_labels=list(EVENTS),
            # BIDS events.tsv duration for all classes. The paper gives 5 s for
            # noise and silence.
            trial_duration=5.25,
            stimulus_type="speech, noise and silence",
            stimulus_modalities=["auditory"],
            primary_modality="auditory",
            synchronicity="synchronous",
            mode="offline",
        ),
        documentation=DocumentationMetadata(
            doi=DOI,
            investigators=[
                "Robert Luke",
                "Eric Larson",
                "Maureen J. Shader",
                "Hamish Innes-Brown",
                "Lindsey Van Yper",
                "Adrian K. C. Lee",
                "Paul F. Sowman",
                "David McAlpine",
            ],
            institution="Macquarie University",
            country="AU",
            repository="OSF",
            data_url=f"https://doi.org/{DATA_DOI}",
            license="CC BY 4.0",
            publication_year=2021,
        ),
        data_structure=DataStructureMetadata(
            n_trials=N_TRIALS_PER_CLASS * len(EVENTS),
            n_trials_per_class={label: N_TRIALS_PER_CLASS for label in EVENTS},
            trials_context="per subject",
        ),
        file_format="BIDS SNIRF",
        external_links={"fresh": "https://openfnirs.org/data/fresh/"},
    )

    _bids_task = TASK
    _bids_session = "01"
    _bids_subject_format = "{:02d}"
    preprocessing_options = {"short_channel_threshold": 0.02}  # noqa: RUF012

    def __init__(self, subjects=None, sessions=None):
        super().__init__(
            subjects=SUBJECTS,
            sessions_per_subject=1,
            events=EVENTS,
            code=CODE,
            interval=INTERVAL,
            paradigm=PARADIGM,
            doi=DOI,
            selected_subjects=subjects,
            selected_sessions=sessions,
            return_all_modalities=True,
        )

    def _download_subject(self, subject, path, force_update, update_path, verbose):
        del update_path
        if subject not in self.subject_list:
            raise ValueError(f"Invalid subject number {subject}")
        bids_root = get_bids_cache_root(CODE, path) / "data"
        expected = bids_root / self._recording_path(subject)
        if expected.is_file() and not force_update:
            return str(bids_root)
        archive_path = Path(dl.data_dl(URL, CODE, path, force_update, verbose))
        bids_root.parent.mkdir(parents=True, exist_ok=True)
        if bids_root.is_dir():
            shutil.rmtree(bids_root)
        extracted = bids_root.parent / "FRESH-Audio"
        if extracted.is_dir():
            shutil.rmtree(extracted)
        extract_archive(archive_path, bids_root.parent)
        if extracted.is_dir():
            extracted.rename(bids_root)
        if not expected.is_file():
            raise FileNotFoundError(f"Archive does not contain {expected}")
        return str(bids_root)

    def _recording_path(self, subject):
        bids_subject = self._bids_subject(subject)
        return Path(
            f"sub-{bids_subject}/ses-01/nirs/"
            f"sub-{bids_subject}_ses-01_task-{TASK}_nirs.snirf"
        )
